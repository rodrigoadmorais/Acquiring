  l.PERIODO, l.SIT_SITE_ID, l.UE_MP_BU_MANAGERIAL, l.UE_MP_SUBBU_MANAGERIAL,
  l.UE_MP_PRODUCT_MANAGERIAL, NUMERACION, l.CAMPO_UE
