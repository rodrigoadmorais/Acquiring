-- -----------------------------------------------------------------------------
-- Saida em formato LONGO: 1 linha por (PERIODO, SITE, BU, SUBBU, PRODUCT, CAMPO_UE)
-- ja classificada nos niveis do mapping PYL:
--     N1_MARGEN    -> MARGEN_MANAGERIAL_NEW      (A., B., C., D., E., F., H.)
--     N2_SUBTOTAL  -> SUBTOTALES_MANAGERIAL_NEW  (A.1, B.5, C.17, D.19, ...)
--     N3_DETALLE   -> PYL_DETAIL_MANAGERIAL_NEW  (A.1.1, C.17.4, ...)
--     N4_UE        -> PYL_MANAGERIAL_UE_NEW / PYL_3_VARCHAR / PYL_4_VARCHAR
--
-- NADA SE PERDE:
--   * TIPO_LINEA = 'PYL'        -> linhas do P&L (e o que se soma)
--   * TIPO_LINEA = 'CONTROL_UE' -> margens que a propria UE entrega
--                                  (Product Monetization, Net Monetization, VC,
--                                  DC, BC, BM, EBIT). Servem para conciliar.
--                                  NAO somar junto com 'PYL'.
--   * TIPO_LINEA = 'RESIDUAL'   -> campos da query que nao existem no mapping.
--                                  Vao para Z.99 com o nome original do campo
--                                  e uma SUGERENCIA de onde encaixar.
--   * Qualquer campo novo que entre no UNPIVOT e nao esteja no CTE `mapa` cai
--     automaticamente em Z.99.99 (nunca desaparece silenciosamente).
--
-- Dialeto: BigQuery (UNPIVOT + GROUP BY ALL). Em outro engine, trocar o UNPIVOT
-- por UNION ALL e o ARRAY<STRUCT<>> por uma tabela/VALUES de mapeamento.
-- =============================================================================

