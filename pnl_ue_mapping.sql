  m.N3_DETALLE                                                               AS N3_DETALLE,
  COALESCE(m.N4_UE      , IF(m.CAMPO_UE IS NULL, l.CAMPO_UE, NULL))          AS N4_UE,
  l.CAMPO_UE,
  COALESCE(m.SUGERENCIA , 'Campo fora do mapping - classificar manualmente')  AS SUGERENCIA,
  l.VALOR
FROM ue_long AS l
LEFT JOIN mapa AS m
  ON m.CAMPO_UE = l.CAMPO_UE
WHERE l.VALOR IS NOT NULL
